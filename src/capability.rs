//! Versioned registry mapping recognized Soroban host imports to protocol
//! capability metadata.
//!
//! WASM modules compiled against the Soroban SDK import a fixed set of host
//! functions. Each one is identified on the wire by a short `(module, name)`
//! pair (for example `("l", "_")` is `put_contract_data`), and each one
//! became available at a specific Stellar protocol version. A contract that
//! newly imports a host function raises the *minimum* protocol version the
//! target network must support before the upgrade can run there.
//!
//! [`REGISTRY`] is generated from the authoritative source of truth for this
//! mapping, `soroban-env-common/env.json` in the
//! [`stellar/rs-soroban-env`](https://github.com/stellar/rs-soroban-env)
//! repository, which the Stellar core team maintains as host functions are
//! added, deprecated, or version-gated. See `docs/capability-registry.md`
//! for the process to regenerate it when a new protocol ships.
//!
//! Any `(module, name)` pair not present in [`REGISTRY`] is unrecognized —
//! it is surfaced to the user as-is and is never assigned a guessed protocol
//! requirement. Unrecognized imports are common: they cover host functions
//! added after this registry was last regenerated, and non-Soroban or
//! provider-specific imports a custom toolchain may introduce.

/// Bumped whenever [`REGISTRY`]'s data changes (entries added, removed, or
/// their `min_protocol` corrected). Consumers that cache classification
/// results keyed by capability id should treat a version change as a cache
/// invalidation signal.
pub const REGISTRY_VERSION: u32 = 1;

/// The Stellar protocol version at which the Soroban host function
/// interface first became available (Soroban's mainnet launch protocol).
/// [`REGISTRY`] entries whose upstream definition carries no explicit
/// `min_supported_protocol` became available at this baseline.
pub const BASELINE_PROTOCOL: u32 = 20;

/// A grouping of related host imports, matching the module namespaces the
/// Soroban host environment exports functions under.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum CapabilityGroup {
    /// Transaction/ledger context: diagnostics, protocol and ledger info,
    /// contract events, structural value comparison.
    Context,
    /// 128/256-bit integer object arithmetic.
    Int,
    /// Map object construction, access, and (de)serialization.
    Map,
    /// Vec object construction, access, and (de)serialization.
    Vec,
    /// Contract instance/data storage, TTL extension, and contract
    /// creation/upload.
    Ledger,
    /// Cross-contract invocation.
    Call,
    /// Bytes/String buffer construction, access, and (de)serialization.
    Buf,
    /// Hashing, signature verification, and key recovery.
    Crypto,
    /// Address object construction, authorization checks, and inspection.
    Address,
    /// Pseudo-random number generation seeded from the transaction.
    Prng,
}

impl CapabilityGroup {
    pub fn as_str(self) -> &'static str {
        match self {
            CapabilityGroup::Context => "Context",
            CapabilityGroup::Int => "Integer",
            CapabilityGroup::Map => "Map",
            CapabilityGroup::Vec => "Vec",
            CapabilityGroup::Ledger => "Ledger/Storage",
            CapabilityGroup::Call => "Cross-Contract Call",
            CapabilityGroup::Buf => "Buffer/Bytes",
            CapabilityGroup::Crypto => "Crypto",
            CapabilityGroup::Address => "Address",
            CapabilityGroup::Prng => "PRNG",
        }
    }
}

/// Protocol capability metadata for one recognized Soroban host import.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct HostImportCapability {
    /// The WASM import module string as it appears on the wire (e.g. `"l"`).
    pub module: &'static str,
    /// The WASM import name string as it appears on the wire (e.g. `"_"`).
    pub name: &'static str,
    /// The descriptive host function name (e.g. `"put_contract_data"`).
    pub function: &'static str,
    /// A stable identifier for this capability, independent of the terse
    /// wire encoding: `"{module}.{function}"` (e.g. `"ledger.put_contract_data"`).
    pub capability_id: &'static str,
    /// The capability group this import belongs to.
    pub group: CapabilityGroup,
    /// The minimum Stellar protocol version on which this import is
    /// available.
    pub min_protocol: u32,
    /// Upstream documentation for this host function.
    pub docs: &'static str,
}

