/// Look up capability metadata for a recognized `(module, name)` import
/// pair. Returns `None` for anything not in [`REGISTRY`] — including
/// non-function imports, deprecated codes, and provider-specific imports —
/// which callers must treat as unknown rather than guessing.
pub fn lookup(module: &str, name: &str) -> Option<&'static HostImportCapability> {
    REGISTRY
        .iter()
        .find(|entry| entry.module == module && entry.name == name)
}

/// The number of recognized capabilities in the registry.
pub fn len() -> usize {
    REGISTRY.len()
}

/// Generate the full capability registry reference as Markdown, grouped by
/// [`CapabilityGroup`] and ordered by protocol version within each group.
pub fn generate_markdown_reference() -> String {
    let mut md = String::new();
    md.push_str("# Soroban Host Import Capability Reference\n\n");
    md.push_str(&format!(
        "Registry version `{}`. Generated from `soroban-env-common/env.json` \
         in [stellar/rs-soroban-env](https://github.com/stellar/rs-soroban-env). \
         See [Updating the Capability Registry](capability-registry.md) for the \
         regeneration process.\n\n",
        REGISTRY_VERSION
    ));
    md.push_str(&format!(
        "{} recognized host imports across {} capability groups. Baseline protocol: `{}`.\n\n",
        REGISTRY.len(),
        [
            CapabilityGroup::Context,
            CapabilityGroup::Int,
            CapabilityGroup::Map,
            CapabilityGroup::Vec,
            CapabilityGroup::Ledger,
            CapabilityGroup::Call,
            CapabilityGroup::Buf,
            CapabilityGroup::Crypto,
            CapabilityGroup::Address,
            CapabilityGroup::Prng,
        ]
        .len(),
        BASELINE_PROTOCOL,
    ));

    let groups = [
        CapabilityGroup::Context,
        CapabilityGroup::Int,
        CapabilityGroup::Map,
        CapabilityGroup::Vec,
        CapabilityGroup::Ledger,
        CapabilityGroup::Call,
        CapabilityGroup::Buf,
        CapabilityGroup::Crypto,
        CapabilityGroup::Address,
        CapabilityGroup::Prng,
    ];

    for group in groups {
        let mut entries: Vec<&HostImportCapability> = REGISTRY
            .iter()
            .filter(|entry| entry.group == group)
            .collect();
        entries.sort_by_key(|entry| (entry.min_protocol, entry.capability_id));

        md.push_str(&format!("## {}\n\n", group.as_str()));
        md.push_str("| Wire Import | Capability ID | Min Protocol | Description |\n");
        md.push_str("| --- | --- | --- | --- |\n");
        for entry in entries {
            md.push_str(&format!(
                "| `{}::{}` | `{}` | {} | {} |\n",
                entry.module,
                entry.name,
                entry.capability_id,
                entry.min_protocol,
                entry.docs.replace('|', "\\|"),
            ));
        }
        md.push('\n');
    }

    md
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn registry_is_non_empty() {
        assert!(REGISTRY.len() > 100, "expected the full host function set");
    }

    #[test]
    fn no_duplicate_wire_keys() {
        let mut seen = std::collections::HashSet::new();
        for entry in REGISTRY {
            assert!(
                seen.insert((entry.module, entry.name)),
                "duplicate wire import ({}, {})",
                entry.module,
                entry.name
            );
        }
    }

    #[test]
    fn no_duplicate_capability_ids() {
        let mut seen = std::collections::HashSet::new();
        for entry in REGISTRY {
            assert!(
                seen.insert(entry.capability_id),
                "duplicate capability id {}",
                entry.capability_id
            );
        }
    }

    #[test]
    fn every_entry_meets_baseline_protocol() {
        for entry in REGISTRY {
            assert!(
                entry.min_protocol >= BASELINE_PROTOCOL,
                "{} claims min_protocol {} below baseline {}",
                entry.capability_id,
                entry.min_protocol,
                BASELINE_PROTOCOL
            );
        }
    }

    #[test]
    fn lookup_finds_known_storage_put() {
        let cap = lookup("l", "_").expect("put_contract_data must be recognized");
        assert_eq!(cap.function, "put_contract_data");
        assert_eq!(cap.group, CapabilityGroup::Ledger);
    }

    #[test]
    fn lookup_returns_none_for_unknown_import() {
        assert!(lookup("z", "not_a_real_import").is_none());
        assert!(lookup("l", "not_a_real_export_code").is_none());
    }

    #[test]
    fn generated_markdown_matches_committed_file() {
        let generated = generate_markdown_reference();
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("docs")
            .join("capability-reference.md");
        let committed = std::fs::read_to_string(&path)
            .unwrap_or_else(|e| panic!("Failed to read {}: {}", path.display(), e));

        if generated != committed.replace("\r\n", "\n") {
            let tmp = std::env::temp_dir().join("capability-reference.generated.md");
            std::fs::write(&tmp, &generated).expect("Failed to write generated content");
            panic!(
                "docs/capability-reference.md is out of date!\n\
                 Generated content written to {}.\n\
                 To update: cp {} {}",
                tmp.display(),
                tmp.display(),
                path.display()
            );
        }
    }
}
