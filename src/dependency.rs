    #[test]
    fn multiple_callers_all_receive_findings() {
        // Both pool and router call token.
        let graph =
            DependencyGraph::from_declarations(&[dep("pool", "token"), dep("router", "token")]);
        let mut findings: HashMap<String, Vec<Finding>> = HashMap::new();
        findings.insert(
            "token".to_string(),
            vec![critical_finding("Function Removed", "transfer")],
        );
        let cross = graph.propagate(&findings);
        let pool_hit = cross.iter().any(|f| f.affected_contract == "pool");
        let router_hit = cross.iter().any(|f| f.affected_contract == "router");
        assert!(pool_hit, "pool must receive the finding");
        assert!(router_hit, "router must receive the finding");
    }

