//! Inter-contract dependency model for cross-contract propagation of breaking changes.
//!
//! In a multi-contract protocol (token + pool + router + factory), a breaking change
//! in one contract's exported interface causes a runtime failure in every contract
//! that calls it — because those callers were compiled against the old interface and
//! do not re-verify it at deploy time.
//!
//! This module provides:
//!
//! - [`ContractDependency`]: a declared edge `caller → callee` with the function names
//!   the caller relies on (or empty, meaning "depends on the whole interface").
//! - [`DependencyGraph`]: the full set of edges with cycle detection and transitive
//!   propagation of breaking changes across contract boundaries.
//! - [`CrossContractFinding`]: a finding that identifies both the changed callee and
//!   the affected caller so it composes into the batch verdict.
//!
//! # Declaration format
//!
//! Dependencies are declared in the batch manifest alongside the contract pairs:
//!
//! ```toml
//! [[pairs]]
//! old  = "token_v1.wasm"
//! new  = "token_v2.wasm"
//! name = "token"
//!
//! [[pairs]]
//! old  = "pool_v1.wasm"
//! new  = "pool_v2.wasm"
//! name = "pool"
//!
//! [[dependencies]]
//! caller   = "pool"            # contract name in [[pairs]]
//! callee   = "token"           # contract name in [[pairs]]
//! functions = ["transfer", "balance"]  # optional; empty means all
//! ```
//!
//! A dependency on a contract absent from the batch is reported as a finding
//! rather than silently ignored, because the safety of the caller cannot be
//! verified without the callee.

use std::collections::{BTreeMap, BTreeSet, HashMap, HashSet, VecDeque};

use serde::{Deserialize, Serialize};

use crate::diff::{Finding, Severity};

// ── Declaration types ────────────────────────────────────────────────────────

/// A single declared dependency from `caller` to `callee`.
///
/// `functions` lists the specific function names the caller uses. When empty
/// (the default), the dependency is on the whole exported interface of the
/// callee — any caller-visible breaking change propagates.
#[derive(Debug, Clone, Deserialize, Serialize, PartialEq, Eq)]
pub struct ContractDependency {
    /// Name of the contract that makes calls (must match a `name` in `[[pairs]]`).
    pub caller: String,
    /// Name of the contract being called (must match a `name` in `[[pairs]]`).
    pub callee: String,
    /// Specific functions the caller relies on. Empty means all functions.
    #[serde(default)]
    pub functions: Vec<String>,
}

// ── Cross-contract finding ───────────────────────────────────────────────────

/// A finding generated by cross-contract propagation.
///
/// It wraps the original finding from the callee's analysis and adds the names
/// of both contracts so the batch report can show "contract B is affected by a
/// breaking change in contract A".
#[derive(Debug, Clone, Serialize)]
pub struct CrossContractFinding {
    /// The contract whose interface broke (the callee).
    pub changed_contract: String,
    /// The contract that depends on the broken interface (the caller).
    pub affected_contract: String,
    /// The underlying finding from the callee's own analysis.
    #[serde(flatten)]
    pub finding: Finding,
    /// How many dependency hops separate `affected_contract` from `changed_contract`.
    /// 1 = direct dependency, 2+ = transitive.
    pub propagation_depth: usize,
}

// ── Dependency graph ─────────────────────────────────────────────────────────

/// The set of all inter-contract edges declared for a batch run.
///
/// Build once with [`DependencyGraph::from_declarations`], then call
/// [`DependencyGraph::propagate`] after the individual pair analyses have run.
#[derive(Debug, Default, Clone)]
pub struct DependencyGraph {
    /// Edges: caller → list of (callee, watched_functions).
    /// Using BTreeMap for deterministic iteration order.
    edges: BTreeMap<String, Vec<(String, Vec<String>)>>,
    /// All contract names that appear in any edge (as caller or callee).
    pub all_referenced: BTreeSet<String>,
}

impl DependencyGraph {
    /// Build the graph from a list of [`ContractDependency`] declarations.
    ///
    /// Repeated declarations of the same `caller` → `callee` pair are merged
    /// into a single edge rather than stored as separate entries, so cycle
    /// detection and propagation each see exactly one edge per pair. Watched
    /// function lists are unioned; if either declaration watches all
    /// functions (an empty list), the merged edge does too.
    pub fn from_declarations(deps: &[ContractDependency]) -> Self {
        let mut graph = Self::default();
        for dep in deps {
            graph.all_referenced.insert(dep.caller.clone());
            graph.all_referenced.insert(dep.callee.clone());

            let caller_edges = graph.edges.entry(dep.caller.clone()).or_default();
            match caller_edges
                .iter_mut()
                .find(|(callee, _)| *callee == dep.callee)
            {
                Some((_, functions)) => {
                    if functions.is_empty() || dep.functions.is_empty() {
                        functions.clear();
                    } else {
                        for f in &dep.functions {
                            if !functions.contains(f) {
                                functions.push(f.clone());
                            }
                        }
                    }
                }
                None => caller_edges.push((dep.callee.clone(), dep.functions.clone())),
            }
        }
        graph
    }

    /// Return names referenced in dependencies but absent from `known_contracts`.
    ///
    /// These are reported as findings so an operator knows the dependency graph
    /// is incomplete for those edges.
    pub fn missing_contracts<'a>(&'a self, known_contracts: &'a HashSet<String>) -> Vec<&'a str> {
        self.all_referenced
            .iter()
            .filter(|name| !known_contracts.contains(*name))
            .map(String::as_str)
            .collect()
    }

    /// Detect cycles in the dependency graph.
    ///
    /// Returns every cycle as an ordered list of contract names (the path that
    /// forms the cycle, with the first and last element being the same contract).
    /// An empty return means the graph is acyclic.
    pub fn detect_cycles(&self) -> Vec<Vec<String>> {
        let mut visited: HashSet<String> = HashSet::new();
        let mut on_stack: HashSet<String> = HashSet::new();
        let mut cycles: Vec<Vec<String>> = Vec::new();
        let mut path: Vec<String> = Vec::new();

        let nodes: Vec<String> = self.edges.keys().cloned().collect();
        for node in nodes {
            if !visited.contains(&node) {
                self.dfs_cycles(&node, &mut visited, &mut on_stack, &mut path, &mut cycles);
            }
        }
        cycles
    }

    fn dfs_cycles(
        &self,
        node: &str,
        visited: &mut HashSet<String>,
        on_stack: &mut HashSet<String>,
        path: &mut Vec<String>,
        cycles: &mut Vec<Vec<String>>,
    ) {
        visited.insert(node.to_string());
        on_stack.insert(node.to_string());
        path.push(node.to_string());

        if let Some(neighbors) = self.edges.get(node) {
            for (callee, _) in neighbors {
                if !visited.contains(callee) {
                    self.dfs_cycles(callee, visited, on_stack, path, cycles);
                } else if on_stack.contains(callee) {
                    // Found a cycle — extract the path from `callee` to here
                    let cycle_start = path.iter().position(|n| n == callee).unwrap_or(0);
                    let mut cycle: Vec<String> = path[cycle_start..].to_vec();
                    cycle.push(callee.clone()); // close the loop
                    cycles.push(cycle);
                }
            }
        }

        path.pop();
        on_stack.remove(node);
    }

    /// Propagate caller-visible breaking changes from callees to their callers.
    ///
    /// For each contract in `contract_findings`, if it has callers that depend on
    /// it, any finding that is caller-visible (i.e. relates to the exported
    /// interface: function removals, signature changes, parameter changes, return
    /// type changes) is propagated to those callers as a [`CrossContractFinding`].
    ///
    /// Propagation is transitive: if A calls B which calls C, and C breaks, the
    /// break propagates B→A as well. The BFS terminates when no new contracts are
    /// reached. Cycles are handled by tracking which (contract, finding_key) pairs
    /// have already been propagated — a cycle generates exactly one finding per
    /// affected contract per root breaking change, then stops.
    ///
    /// `contract_findings` maps contract name → list of findings from that contract's
    /// own analysis. Only caller-visible findings (by category) are propagated.
    pub fn propagate(
        &self,
        contract_findings: &HashMap<String, Vec<Finding>>,
    ) -> Vec<CrossContractFinding> {
        // Build a reverse map: callee → list of (caller, watched_functions)
        let mut callee_to_callers: BTreeMap<String, Vec<(String, Vec<String>)>> = BTreeMap::new();
        for (caller, edges) in &self.edges {
            for (callee, funcs) in edges {
                callee_to_callers
                    .entry(callee.clone())
                    .or_default()
                    .push((caller.clone(), funcs.clone()));
            }
        }

        let mut result: Vec<CrossContractFinding> = Vec::new();
        // Track (affected_contract, changed_contract, finding_key) to prevent
        // duplicate findings and to terminate cycles.
        let mut emitted: HashSet<(String, String, String)> = HashSet::new();

        // Seed the BFS with caller-visible findings from each callee.
        // Queue entries: (changed_contract, affected_contract, finding, depth)
        let mut queue: VecDeque<(String, String, Finding, usize)> = VecDeque::new();

        for (callee, findings) in contract_findings {
            for finding in findings {
                if !is_caller_visible(finding) {
                    continue;
                }
                if let Some(callers) = callee_to_callers.get(callee) {
                    for (caller, watched_fns) in callers {
                        if !function_is_watched(finding, watched_fns) {
                            continue;
                        }
                        let key = propagation_key(callee, finding);
                        let dedup = (caller.clone(), callee.clone(), key);
                        if emitted.insert(dedup) {
                            queue.push_back((callee.clone(), caller.clone(), finding.clone(), 1));
                        }
                    }
                }
            }
        }

        // BFS: propagate transitively, one hop at a time.
        while let Some((changed, affected, finding, depth)) = queue.pop_front() {
            result.push(CrossContractFinding {
                changed_contract: changed.clone(),
                affected_contract: affected.clone(),
                finding: finding.clone(),
                propagation_depth: depth,
            });

            // Now propagate from `affected` to its own callers.
            if let Some(callers_of_affected) = callee_to_callers.get(&affected) {
                for (caller_of_caller, watched_fns) in callers_of_affected {
                    if !function_is_watched(&finding, watched_fns) {
                        continue;
                    }
                    let key = propagation_key(&changed, &finding);
                    let dedup = (caller_of_caller.clone(), changed.clone(), key);
                    if emitted.insert(dedup) {
                        queue.push_back((
                            changed.clone(),
                            caller_of_caller.clone(),
                            finding.clone(),
                            depth + 1,
                        ));
                    }
                }
            }
        }

        // Sort for determinism: by depth, then changed, then affected, then target.
        result.sort_by(|a, b| {
            a.propagation_depth
                .cmp(&b.propagation_depth)
                .then_with(|| a.changed_contract.cmp(&b.changed_contract))
                .then_with(|| a.affected_contract.cmp(&b.affected_contract))
                .then_with(|| a.finding.target.cmp(&b.finding.target))
        });

        result
    }
}

// ── Propagation helpers ──────────────────────────────────────────────────────

/// Categories that are visible to a cross-contract caller.
///
/// Storage, documentation, and info findings are internal to a contract and
/// irrelevant to callers. A caller cares about what it can *call*: function
/// presence, parameter shapes, return types, and cascading type breaks (which
/// can change the types a function accepts or returns).
const CALLER_VISIBLE_CATEGORIES: &[&str] = &[
    "Function Removed",
    "Function Signature Changed",
    "Parameter Renamed",
    "Parameter Reordered",
    "Parameter Type Changed",
    "Return Type Changed",
    "Struct Removed",
    "Struct Field Removed",
    "Struct Field Reordered",
    "Struct Field Type Changed",
    "Struct Field Inserted",
    "Enum Removed",
    "Enum Case Removed",
    "Enum Case Value Changed",
    "Union Removed",
    "Union Case Removed",
    "Union Case Reordered",
    "Union Case Type Changed",
    "Union Case Inserted",
    "Error Enum Removed",
    "Error Enum Case Removed",
    "Error Enum Case Value Changed",
    "Cascading Layout Break",
];

/// Whether a finding is visible to contracts that call the changed contract.
///
/// We propagate `Critical` and `Warning` findings only — `Info` findings like
/// "Function Added" or "Enum Case Added" are not breaking for a caller.
pub fn is_caller_visible(finding: &Finding) -> bool {
    if finding.severity == Severity::Info {
        return false;
    }
    CALLER_VISIBLE_CATEGORIES
        .iter()
        .any(|&cat| finding.category == cat)
}

/// Whether the finding relates to a function the caller explicitly listed.
///
/// When `watched_fns` is empty the caller depends on the whole interface, so
/// every caller-visible finding passes. When it is non-empty only findings
/// whose `target` starts with one of the watched function names pass.
fn function_is_watched(finding: &Finding, watched_fns: &[String]) -> bool {
    if watched_fns.is_empty() {
        return true;
    }
    let target = match finding.target.as_deref() {
        Some(t) => t,
        // Targetless findings (e.g. environment metadata) are always considered
        // relevant when no function filter is set; with a filter, skip them
        // since they do not belong to any specific function.
        None => return false,
    };
    watched_fns
        .iter()
        .any(|fn_name| target == fn_name.as_str() || target.starts_with(&format!("{}.", fn_name)))
}

/// A stable string key for a finding used to deduplicate propagated copies.
fn propagation_key(contract: &str, finding: &Finding) -> String {
    format!(
        "{}|{}|{}",
        contract,
        finding.category,
        finding.target.as_deref().unwrap_or("")
    )
}

// ── Cycle and missing-contract findings ─────────────────────────────────────

/// Build findings for cyclic dependencies.
///
/// A cycle is not automatically an error — the contracts can still be analyzed
/// individually — but it must be reported clearly so an operator knows the
/// upgrade ordering matters.
pub fn cycle_findings(cycles: &[Vec<String>]) -> Vec<Finding> {
    cycles
        .iter()
        .map(|cycle| {
            let path = cycle.join(" → ");
            Finding {
                axes: Vec::new(),
                severity: Severity::Warning,
                category: "Cyclic Contract Dependency".to_string(),
                message: format!(
                    "Cyclic dependency detected: {}. \
                     Upgrade order matters — deploying these contracts in the wrong order \
                     may leave the protocol in an inconsistent state.",
                    path
                ),
                type_name: None,
                target: Some(cycle[0].clone()),
                change: None,
                root_target: None,
            }
        })
        .collect()
}

/// Build findings for dependencies on contracts absent from the batch.
///
/// When a declared callee is not present in the batch, the safety of its callers
/// cannot be verified. This is reported at `Warning` severity — the analysis of
/// the caller still runs, but its verdict is incomplete.
pub fn missing_contract_findings(missing: &[&str]) -> Vec<Finding> {
    missing
        .iter()
        .map(|name| Finding {
            axes: Vec::new(),
            severity: Severity::Warning,
            category: "Missing Dependency Contract".to_string(),
            message: format!(
                "Contract '{}' is declared as a dependency but is not present in this batch run. \
                 The safety of contracts that depend on '{}' cannot be fully verified.",
                name, name
            ),
            type_name: None,
            target: Some(name.to_string()),
            change: None,
            root_target: None,
        })
        .collect()
}

